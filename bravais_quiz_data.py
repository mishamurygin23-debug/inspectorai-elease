def relation_str(params):
    """Строка вида 'a=b!=c, альфа=бета=гамма=90' по параметрам ячейки."""
    a, b, c, alpha, beta, gamma = params

    def group(vals, names):
        groups = []
        for i, v in enumerate(vals):
            placed = False
            for g in groups:
                if abs(vals[g[0]] - v) < 1e-6:
                    g.append(i)
                    placed = True
                    break
            if not placed:
                groups.append([i])
        groups.sort(key=lambda g: g[0])
        return "!=".join("=".join(names[i] for i in g) for g in groups)

    sides = group([a, b, c], ["a", "b", "c"])
    angles_part = group([alpha, beta, gamma], ["альфа", "бета", "гамма"])

    if alpha == beta == gamma:
        angles_part += f"={alpha:g} град."

    return f"{sides},  {angles_part}"


def get_frac_points(centering):
    """Возвращает (вершины ячейки, все узлы решётки в ней) в дробных координатах."""
    corners = [(x, y, z) for x in (0, 1) for y in (0, 1) for z in (0, 1)]
    pts = list(corners)
    if centering == "I":
        pts.append((0.5, 0.5, 0.5))
    elif centering == "F":
        pts += [(0.5, 0.5, 0), (0.5, 0.5, 1),
                (0.5, 0, 0.5), (0.5, 1, 0.5),
                (0, 0.5, 0.5), (1, 0.5, 0.5)]
    elif centering == "C":
        pts += [(0.5, 0.5, 0), (0.5, 0.5, 1)]
    return corners, pts


def get_edges(corners):
    """12 рёбер параллелепипеда — пары вершин, отличающихся ровно одной координатой."""
    edges = []
    for i, c1 in enumerate(corners):
        for c2 in corners[i + 1:]:
            if sum(a != b for a, b in zip(c1, c2)) == 1:
                edges.append((c1, c2))
    return edges


def to_cart(points_frac, matrix):
    return np.array(points_frac, dtype=float) @ matrix


def draw_lattice(ax, key, show_title=False, show_relation=False):
    info = LATTICES[key]
    a, b, c, alpha, beta, gamma = info["params"]
    matrix = lattice_vectors(a, b, c, alpha, beta, gamma)

    corners, pts = get_frac_points(info["centering"])
    edges = get_edges(corners)

    cart_corners = to_cart(corners, matrix)
    cart_pts = to_cart(pts, matrix)

    for c1, c2 in edges:
        p1, p2 = to_cart([c1], matrix)[0], to_cart([c2], matrix)[0]
        ax.plot(*zip(p1, p2), color="gray", linewidth=1.5, alpha=0.7)

    ax.scatter(cart_pts[:, 0], cart_pts[:, 1], cart_pts[:, 2],
               s=160, color="tab:blue", edgecolor="black", depthshade=True)

    ranges = cart_corners.max(axis=0) - cart_corners.min(axis=0)
    ranges = np.where(ranges == 0, 1, ranges)
    ax.set_box_aspect(ranges)

    ax.set_xticks([])
    ax.set_yticks([])
    ax.set_zticks([])
    ax.set_axis_off()

    if show_title:
        ax.set_title(f"{info['name']}\n{relation_str(info['params'])}", fontsize=8.5)
    elif show_relation:
        ax.set_title(relation_str(info["params"]), fontsize=10)


