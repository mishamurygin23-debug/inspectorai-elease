def lattice_vectors(a, b, c, alpha_deg, beta_deg, gamma_deg):
    """Базисные векторы (a1, a2, a3) ячейки по параметрам a, b, c, alpha, beta, gamma."""
    alpha = np.radians(alpha_deg)
    beta = np.radians(beta_deg)
    gamma = np.radians(gamma_deg)

    a1 = np.array([a, 0.0, 0.0])
    a2 = np.array([b * np.cos(gamma), b * np.sin(gamma), 0.0])

    cx = c * np.cos(beta)
    cy = c * (np.cos(alpha) - np.cos(beta) * np.cos(gamma)) / np.sin(gamma)
    cz_sq = c ** 2 - cx ** 2 - cy ** 2
    cz = np.sqrt(max(cz_sq, 0.0))
    a3 = np.array([cx, cy, cz])

    return np.array([a1, a2, a3])


